package main

import (
	"fmt"
)

// 定义一个简单的结构体，用于模拟 AI 算力节点
type Node struct {
	ID     int
	Status string
}

func main() {
	// ------------------------------------------------
	// 1. 整数家族 (内存排查、掩码计算常用)
	// ------------------------------------------------
	num := 255
	fmt.Println("--- 整数族 ---")
	fmt.Printf("%%d (十进制)   : %d\n", num)
	fmt.Printf("%%x (十六进制) : %x\n", num) // 排查内存地址或 Hash 冲突时最常用
	fmt.Printf("%%X (大写十六) : %X\n", num)
	fmt.Printf("%%o (八进制)   : %o\n", num) // Linux 文件权限 (如 chmod 777) 常用
	fmt.Printf("%%b (二进制)   : %b\n", num) // AI 底层位运算 (Bitwise) 排错必备

	// ------------------------------------------------
	// 2. 浮点数家族 (大模型参数、延迟统计常用)
	// ------------------------------------------------
	pi := 3.141592653589793
	fmt.Println("\n--- 浮点数族 ---")
	fmt.Printf("%%f (标准浮点) : %f\n", pi)    // 默认保留 6 位小数
	fmt.Printf("%%.2f (限小数位): %.2f\n", pi) // 💡 常用：强行指定保留 2 位小数
	fmt.Printf("%%e (科学计数) : %e\n", pi)    // 长尾极小梯度值（如 1e-7）常用
	fmt.Printf("%%g (紧凑模式) : %g\n", pi)    // 自动去掉末尾无用的 0，最智能，日志里最爱用

	// ------------------------------------------------
	// 3. 布尔与字符
	// ------------------------------------------------
	fmt.Println("\n--- 布尔与字符 ---")
	isActive := true
	fmt.Printf("%%t (布尔值)   : %t\n", isActive)

	var char rune = '🚀' // rune 是 int32 的别名，代表一个 Unicode 码点
	fmt.Printf("%%c (Unicode)  : %c\n", char)

	// ------------------------------------------------
	// 4. 字符串家族 (解析配置文件常用)
	// ------------------------------------------------
	fmt.Println("\n--- 字符串族 ---")
	str := "AI Infra"
	sneakyStr := "AI Infra   " // 注意：末尾有隐形空格

	fmt.Printf("%%s (纯字符串) : %s\n", str)
	fmt.Printf("%%s (纯字符串) : %s\n", sneakyStr)
	// 💡 排障杀手锏：如果你怀疑读到的环境变量或配置首尾有看不见的空格或换行符，用 %q！
	fmt.Printf("%%q (带引号串) : %q\n", sneakyStr)
	fmt.Printf("%%q (带引号符) : %q\n", char)

	// ------------------------------------------------
	// 5. 万能探测器 (调试未知变量的核武器)
	// ------------------------------------------------
	fmt.Println("\n--- 万能探测器 ---")
	node := Node{ID: 10086, Status: "Running"}

	fmt.Printf("%%v (自然形式) : %v\n", node)   // 只打印值：{10086 Running}
	fmt.Printf("%%+v(带字段名) : %+v\n", node)  // 💡 极度推荐：打印结构体时带上字段名，排错利器！
	fmt.Printf("%%#v(Go语法格式): %#v\n", node) // 终极利器：打印出可以直接粘贴回代码里的完整 Go 语法格式
	fmt.Printf("%%T (类型探测) : %T\n", node)   // 打印变量的真实底层类型

	// 百分号本身
	fmt.Printf("%%%% (字面量)   : 训练进度 100%%\n")
}
